"""
예제 13-7: 무한 루프 — while 루프에서 증감 누락 (수정 완료)
============================================================
수정: while 루프 안에 카운터 증가 구문(count += 1) 추가
"""

# 수정된 코드: 카운터 증가 구문 추가
print("1부터 5까지 출력합니다:")

count = 1
while count <= 5:
    print(f"  현재 값: {count}")
    count += 1                    # ← 이 줄을 추가하여 무한 루프 해결!

print(f"완료! (마지막 count 값: {count})")

# 더 안전한 방법: for 루프 사용
print("\nfor 루프로 같은 작업:")
for i in range(1, 6):
    print(f"  현재 값: {i}")

print("완료!")
